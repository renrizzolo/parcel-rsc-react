import { describe, expect, it } from "vitest";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repoRoot = path.dirname(path.dirname(packageRoot));
const configPackageRoot = path.join(
  repoRoot,
  "packages/parcel-config-rsc-router"
);
const parcelBin = path.join(
  repoRoot,
  "apps/my-static-site/node_modules/parcel/bin/parcel"
);

function installNativePluginFixture(baseDir: string) {
  const pluginDir = path.join(
    baseDir,
    "node_modules/@renr/parcel-plugin-rsc-router"
  );
  const releaseDir = path.join(pluginDir, "target/release");
  fs.mkdirSync(releaseDir, { recursive: true });
  fs.copyFileSync(
    path.join(packageRoot, "package.json"),
    path.join(pluginDir, "package.json")
  );
  for (const file of fs.readdirSync(path.join(packageRoot, "target/release"))) {
    if (
      file.endsWith(".dll") ||
      file.endsWith(".so") ||
      file.endsWith(".dylib")
    ) {
      fs.copyFileSync(
        path.join(packageRoot, "target/release", file),
        path.join(releaseDir, file)
      );
    }
  }
}

function installConfigPackageFixture(baseDir: string) {
  const configDir = path.join(
    baseDir,
    "node_modules/@renr/parcel-config-rsc-router"
  );
  fs.mkdirSync(configDir, { recursive: true });
  fs.copyFileSync(
    path.join(configPackageRoot, "package.json"),
    path.join(configDir, "package.json")
  );
  fs.copyFileSync(
    path.join(configPackageRoot, "index.json"),
    path.join(configDir, "index.json")
  );
}

function createSamplePages(appDir: string) {
  const pagesDir = path.join(appDir, "src/pages");
  fs.mkdirSync(path.join(pagesDir, "blog"), { recursive: true });
  fs.writeFileSync(
    path.join(pagesDir, "index.tsx"),
    "export default function Home() { return null; }\n"
  );
  fs.writeFileSync(
    path.join(pagesDir, "blog/post.tsx"),
    "export default function Post() { return null; }\n"
  );
  fs.writeFileSync(
    path.join(appDir, "entry.js"),
    'console.log("hello from host fixture");\n'
  );
}

function runParcelBuild(appDir: string, cwd: string) {
  return spawnSync(
    process.execPath,
    [
      parcelBin,
      "build",
      path.join(appDir, "entry.js"),
      "--config",
      path.join(appDir, ".parcelrc"),
      "--dist-dir",
      path.join(appDir, "dist"),
    ],
    {
      cwd,
      encoding: "utf8",
      maxBuffer: 32 * 1024 * 1024,
    }
  );
}

describe("native plugin host integration (Parcel v3 C ABI)", () => {
  it("loads the compiled native plugin DLL in Parcel v3 and generates routes.ts", () => {
    const tmpDir = fs.mkdtempSync(
      path.join(os.tmpdir(), "parcel-native-plugin-host-")
    );

    try {
      createSamplePages(tmpDir);
      installNativePluginFixture(tmpDir);

      fs.writeFileSync(
        path.join(tmpDir, "package.json"),
        JSON.stringify(
          {
            name: "host-fixture",
            private: true,
            "@renr/parcel-plugin-rsc-router": {
              source: "src/pages/**/*.tsx",
              output: "src/routes.ts",
            },
          },
          null,
          2
        )
      );

      fs.writeFileSync(
        path.join(tmpDir, ".parcelrc"),
        JSON.stringify(
          {
            extends: "@parcel/config-default",
            reporters: ["...", "@renr/parcel-plugin-rsc-router"],
          },
          null,
          2
        )
      );

      const result = runParcelBuild(tmpDir, tmpDir);
      expect(result.status, result.stderr || result.stdout).toBe(0);

      const routesFile = path.join(tmpDir, "src/routes.ts");
      expect(fs.existsSync(routesFile)).toBe(true);

      const routesContent = fs.readFileSync(routesFile, "utf8");
      expect(routesContent).toContain(
        "// This file is auto-generated by @renr/parcel-plugin-rsc-router."
      );
      expect(routesContent).toContain('"/blog/post"');
      expect(routesContent).toContain('"/index.html"');
      expect(routesContent).not.toContain("prerenderStaticSite");
    } finally {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    }
  });

  it("resolves relative .parcelrc inline config paths even when invoked from a different cwd", () => {
    const tmpDir = fs.mkdtempSync(
      path.join(os.tmpdir(), "parcel-native-plugin-rc-cfg-")
    );
    const appDir = path.join(tmpDir, "app");

    try {
      fs.mkdirSync(appDir, { recursive: true });
      createSamplePages(appDir);
      installNativePluginFixture(appDir);

      fs.writeFileSync(
        path.join(appDir, "package.json"),
        JSON.stringify({ name: "rc-config-fixture", private: true }, null, 2)
      );

      fs.writeFileSync(
        path.join(appDir, ".parcelrc"),
        JSON.stringify(
          {
            extends: "@parcel/config-default",
            reporters: [
              "...",
              {
                plugin: "@renr/parcel-plugin-rsc-router",
                config: {
                  source: "./src/pages/**/*.tsx",
                  output: "./src/routes.ts",
                },
              },
            ],
          },
          null,
          2
        )
      );

      const result = runParcelBuild(appDir, tmpDir);
      expect(result.status, result.stderr || result.stdout).toBe(0);

      const routesFile = path.join(appDir, "src/routes.ts");
      expect(fs.existsSync(routesFile)).toBe(true);

      const routesContent = fs.readFileSync(routesFile, "utf8");
      expect(routesContent).toContain('"/blog/post"');
      expect(routesContent).toContain('"/index.html"');
    } finally {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    }
  });

  it("discovers app package.json via .parcelrc location in monorepos when invoked from repo root", () => {
    const monorepoDir = fs.mkdtempSync(
      path.join(os.tmpdir(), "parcel-native-plugin-monorepo-")
    );
    const appDir = path.join(monorepoDir, "apps/my-app");

    try {
      fs.mkdirSync(appDir, { recursive: true });
      createSamplePages(appDir);
      installNativePluginFixture(appDir);

      fs.writeFileSync(
        path.join(monorepoDir, "package.json"),
        JSON.stringify({ name: "monorepo-root", private: true }, null, 2)
      );

      fs.writeFileSync(
        path.join(appDir, "package.json"),
        JSON.stringify(
          {
            name: "my-app",
            private: true,
            "@renr/parcel-plugin-rsc-router": {
              source: "src/pages/**/*.tsx",
              output: "src/routes.ts",
            },
          },
          null,
          2
        )
      );

      fs.writeFileSync(
        path.join(appDir, ".parcelrc"),
        JSON.stringify(
          {
            extends: "@parcel/config-default",
            reporters: ["...", "@renr/parcel-plugin-rsc-router"],
          },
          null,
          2
        )
      );

      const result = runParcelBuild(appDir, monorepoDir);
      expect(result.status, result.stderr || result.stdout).toBe(0);

      const routesFile = path.join(appDir, "src/routes.ts");
      expect(fs.existsSync(routesFile)).toBe(true);

      const routesContent = fs.readFileSync(routesFile, "utf8");
      expect(routesContent).toContain('"/blog/post"');
      expect(routesContent).toContain('"/index.html"');
    } finally {
      fs.rmSync(monorepoDir, { recursive: true, force: true });
    }
  });

  it("loads via @renr/parcel-config-rsc-router and generates routes.ts for the app", () => {
    const tmpDir = fs.mkdtempSync(
      path.join(os.tmpdir(), "parcel-native-plugin-config-")
    );

    try {
      createSamplePages(tmpDir);
      installNativePluginFixture(tmpDir);
      installConfigPackageFixture(tmpDir);

      fs.writeFileSync(
        path.join(tmpDir, "package.json"),
        JSON.stringify(
          {
            name: "config-fixture",
            private: true,
            "@renr/parcel-plugin-rsc-router": {
              source: "src/pages/**/*.tsx",
              output: "src/routes.ts",
            },
          },
          null,
          2
        )
      );

      fs.writeFileSync(
        path.join(tmpDir, ".parcelrc"),
        JSON.stringify(
          {
            extends: "@renr/parcel-config-rsc-router",
          },
          null,
          2
        )
      );

      const result = runParcelBuild(tmpDir, tmpDir);
      expect(result.status, result.stderr || result.stdout).toBe(0);

      const routesFile = path.join(tmpDir, "src/routes.ts");
      expect(fs.existsSync(routesFile)).toBe(true);

      const routesContent = fs.readFileSync(routesFile, "utf8");
      expect(routesContent).toContain(
        "// This file is auto-generated by @renr/parcel-plugin-rsc-router."
      );
      expect(routesContent).toContain('"/blog/post"');
      expect(routesContent).toContain('"/index.html"');
      expect(routesContent).not.toContain("prerenderStaticSite");
    } finally {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    }
  });
});
